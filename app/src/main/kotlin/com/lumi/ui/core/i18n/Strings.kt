package com.lumi.ui.core.i18n

import androidx.compose.runtime.Composable
import androidx.compose.runtime.compositionLocalOf
import java.util.Locale

/**
 * Lightweight in-app localisation. LUMI ships with English and Russian; the language follows the
 * system locale unless the user overrides it in Settings. Keys missing from a table fall back to
 * English, then to the key itself, so a missing translation never breaks a screen.
 */
enum class LumiLang(val tag: String, val label: String) {
    SYSTEM("system", "System"),
    EN("en", "English"),
    RU("ru", "Русский"),
}

val LocalLang = compositionLocalOf { LumiLang.EN }

@Composable
fun tr(key: String): String = Strings.tr(key, LocalLang.current)

object Strings {

    fun resolve(lang: LumiLang): LumiLang = when (lang) {
        LumiLang.SYSTEM -> if (Locale.getDefault().language.startsWith("ru")) LumiLang.RU else LumiLang.EN
        else -> lang
    }

    fun tr(key: String, lang: LumiLang): String {
        val l = resolve(lang)
        return when (l) {
            LumiLang.RU -> Ru[key] ?: En[key] ?: key
            else -> En[key] ?: key
        }
    }

